package update

import (
	"bufio"
	"crypto/rand"
	"encoding/hex"
	"regexp"
	"strings"
)

var envLine = regexp.MustCompile(`^([A-Z][A-Z0-9_]*)=(.*)$`)

// envKeys are the parameters set in a .env text, in their order.
func envKeys(text string) (keys []string, vals map[string]string) {
	vals = map[string]string{}
	sc := bufio.NewScanner(strings.NewReader(text))
	sc.Buffer(make([]byte, 64*1024), 1<<20)
	for sc.Scan() {
		if m := envLine.FindStringSubmatch(strings.TrimSpace(sc.Text())); m != nil {
			if _, seen := vals[m[1]]; !seen {
				keys = append(keys, m[1])
			}
			vals[m[1]] = m[2]
		}
	}
	return keys, vals
}

// secretKey says whether a parameter is a password or a secret of the installation itself, generated when empty:
// …_PASSWORD, …_PASS, …_SECRET, …_SECRET_KEY. The client secrets of outside services (…CLIENT_SECRET of Google,
// Microsoft) are not generated: they come from those services, empty turns the service off.
func secretKey(k string) bool {
	if strings.Contains(k, "CLIENT_") {
		return false
	}
	for _, s := range []string{"_PASSWORD", "_PASS", "_SECRET", "_SECRET_KEY"} {
		if strings.HasSuffix(k, s) {
			return true
		}
	}
	return false
}

// RandomSecret is 32 random bytes in hex, as openssl rand -hex 32.
func RandomSecret() string {
	b := make([]byte, 32)
	if _, err := rand.Read(b); err != nil {
		panic(err)
	}
	return hex.EncodeToString(b)
}

// MergeEnv adds to env (deploy/.env) the parameters of example (deploy/.env.example of the new version) it lacks:
// with the example's value, an empty password or secret generated by gen. The lines already in env are kept as they
// are. It returns the new text and the names added.
func MergeEnv(env, example, version string, gen func() string) (string, []string) {
	_, have := envKeys(env)
	keys, vals := envKeys(example)
	var add []string
	var b strings.Builder
	for _, k := range keys {
		if _, ok := have[k]; ok {
			continue
		}
		v := vals[k]
		if v == "" && secretKey(k) {
			v = gen()
		}
		add = append(add, k)
		b.WriteString(k + "=" + v + "\n")
	}
	if len(add) == 0 {
		return env, nil
	}
	if env != "" && !strings.HasSuffix(env, "\n") {
		env += "\n"
	}
	return env + "# added by go24-updater " + version + " from .env.example\n" + b.String(), add
}
