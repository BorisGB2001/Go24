-- «Генератор документов → Права доступа» (GO24DEV-987, documentgenerator.role.*): roles give each
-- right a level — templates (changing templates: none, all), view (seeing the documents of the cards: none, all),
-- modify (making, making again and deleting them, the public link: none, all), settings («Моя компания», the stamp
-- and the facsimiles, the numerators: none, all). Members are employees or departments (with the ones below). A person
-- has the highest level of their roles; one without roles has the default role's. Administrators have every right.
CREATE TABLE docgen_roles (
    id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    num        bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE, -- documentgenerator.role.* knows roles by numbers
    code       text UNIQUE,             -- a built-in role: its name comes from the locales (docroles.role.<code>)
    name       text NOT NULL DEFAULT '' CHECK (length(name) <= 100),
    is_default boolean NOT NULL DEFAULT false,
    perms      jsonb NOT NULL DEFAULT '{}', -- {"templates": "none", "view": "all", "modify": "all", "settings": "none"}
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (code IS NOT NULL OR name <> '')
);
CREATE UNIQUE INDEX docgen_roles_default_idx ON docgen_roles (is_default) WHERE is_default;
CREATE TABLE docgen_role_members (
    id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    role_id       uuid NOT NULL REFERENCES docgen_roles(id) ON DELETE CASCADE,
    user_id       uuid REFERENCES users(id) ON DELETE CASCADE,
    department_id uuid REFERENCES departments(id) ON DELETE CASCADE,
    CHECK ((user_id IS NULL) <> (department_id IS NULL))
);
CREATE UNIQUE INDEX docgen_role_members_user_idx ON docgen_role_members (role_id, user_id) WHERE user_id IS NOT NULL;
CREATE UNIQUE INDEX docgen_role_members_dept_idx ON docgen_role_members (role_id, department_id) WHERE department_id IS NOT NULL;
