-- REST compatible with the portal, the drive (GO24DEV-886): integrations know storages, folders and files by numbers
-- (disk.storage.get, disk.folder.getchildren, disk.file.get). Folders and files are numbered from one sequence, as
-- the objects of the drive: given once, in the order of creation, never reused. A storage is one
-- of go24's drives — a person's «Мой диск», a project's, the company's — numbered when an integration first sees it;
-- its ROOT_OBJECT_ID, the folder of its top, is a number of the same sequence.
CREATE SEQUENCE portal_disk_objects_num;
ALTER TABLE drive_folders ADD COLUMN num bigint;
ALTER TABLE files ADD COLUMN num bigint;
WITH o AS (
    SELECT id, created_at, false AS file FROM drive_folders
    UNION ALL SELECT id, created_at, true FROM files),
n AS (SELECT id, file, row_number() OVER (ORDER BY created_at, file, id) n FROM o)
UPDATE drive_folders x SET num = n.n FROM n WHERE NOT n.file AND n.id = x.id;
WITH o AS (
    SELECT id, created_at, false AS file FROM drive_folders
    UNION ALL SELECT id, created_at, true FROM files),
n AS (SELECT id, file, row_number() OVER (ORDER BY created_at, file, id) n FROM o)
UPDATE files x SET num = n.n FROM n WHERE n.file AND n.id = x.id;
SELECT setval('portal_disk_objects_num', greatest(coalesce((SELECT max(num) FROM drive_folders), 0),
    coalesce((SELECT max(num) FROM files), 0)) + 1, false);
ALTER TABLE drive_folders ALTER COLUMN num SET DEFAULT nextval('portal_disk_objects_num'), ALTER COLUMN num SET NOT NULL,
    ADD UNIQUE (num);
ALTER TABLE files ALTER COLUMN num SET DEFAULT nextval('portal_disk_objects_num'), ALTER COLUMN num SET NOT NULL,
    ADD UNIQUE (num);

CREATE TABLE portal_disk_storages (
    num        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    root_num   bigint NOT NULL UNIQUE DEFAULT nextval('portal_disk_objects_num'), -- the folder of the drive's top
    user_id    uuid UNIQUE REFERENCES users(id) ON DELETE CASCADE,              -- the person's «Мой диск»
    project_id uuid UNIQUE REFERENCES projects(id) ON DELETE CASCADE,           -- a project's (a collab's)
    company    boolean NOT NULL DEFAULT false,                                   -- «Общий диск»
    CHECK (num_nonnulls(user_id, project_id) + company::int = 1)
);
CREATE UNIQUE INDEX portal_disk_storages_company ON portal_disk_storages (company) WHERE company;
