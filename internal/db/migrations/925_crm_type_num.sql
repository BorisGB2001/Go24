-- REST compatible with the portal, crm.item.* and crm.type.* (GO24DEV-952): a smart process has its number
-- («entityTypeId»), from 128, given once in the order of creation and never reused.
ALTER TABLE crm_types ADD COLUMN num bigint;
UPDATE crm_types t SET num = o.n FROM (SELECT id, 127 + row_number() OVER (ORDER BY created_at, id) n FROM crm_types) o WHERE o.id = t.id;
ALTER TABLE crm_types ALTER COLUMN num SET NOT NULL, ADD UNIQUE (num);
DO $$ BEGIN
    EXECUTE format('ALTER TABLE crm_types ALTER COLUMN num ADD GENERATED BY DEFAULT AS IDENTITY (MINVALUE 128 START WITH %s)',
                   (SELECT coalesce(max(num), 127) + 1 FROM crm_types));
END $$;
