-- Calls of an outside PBX told by REST telephony.externalcall.* (GO24DEV-921): a call registered and
-- not finished yet, the external lines of telephony.externalLine.*, and what voximplant.statistic.get gives of a call.

CREATE TABLE telephony_external (
    call_id      text PRIMARY KEY,                  -- CALL_ID: externalCall.<hex>.<unix time>
    user_id      uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    number       text NOT NULL,
    line         text NOT NULL DEFAULT '',
    type         smallint NOT NULL DEFAULT 1,       -- 1 outgoing, 2 incoming, 3 incoming redirected, 4 callback, 5 info
    crm_entity   text NOT NULL DEFAULT '',
    crm_id       uuid,
    lead_created boolean NOT NULL DEFAULT false,
    started_at   timestamptz NOT NULL DEFAULT now(),
    record       text NOT NULL DEFAULT '',          -- a record attached before the call finished
    notify_ids   bigint[] NOT NULL DEFAULT '{}',    -- the notifications of the call card shown (show/hide)
    created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE telephony_ext_lines (
    number          text PRIMARY KEY,
    name            text NOT NULL DEFAULT '',
    crm_auto_create boolean NOT NULL DEFAULT true,
    created_at      timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE telephony_calls
    ADD COLUMN num bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    ADD COLUMN cost numeric(12, 2) NOT NULL DEFAULT 0,
    ADD COLUMN cost_currency text NOT NULL DEFAULT '',
    ADD COLUMN failed_code text NOT NULL DEFAULT '',          -- CALL_FAILED_CODE told by the outside PBX
    ADD COLUMN failed_reason text NOT NULL DEFAULT '',
    ADD COLUMN external boolean NOT NULL DEFAULT false;
