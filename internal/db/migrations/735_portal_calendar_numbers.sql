-- REST compatible with the portal, the calendar (GO24DEV-873): integrations know meetings and calendars (sections) by
-- numbers (calendar.event.get, calendar.section.get). A meeting's number is given once, in the order of creation, never
-- reused. A section is one of go24's calendars: a person's main one, one of their own, a project's, the
-- company's — each gets its number when an integration first sees it.
ALTER TABLE events ADD COLUMN num bigint;
UPDATE events x SET num = o.n FROM (SELECT id, row_number() OVER (ORDER BY created_at, id) n FROM events) o WHERE o.id = x.id;
ALTER TABLE events ALTER COLUMN num SET NOT NULL, ADD UNIQUE (num);
DO $$
DECLARE
    next bigint;
BEGIN
    SELECT coalesce(max(num), 0) + 1 FROM events INTO next;
    EXECUTE format('ALTER TABLE events ALTER COLUMN num ADD GENERATED BY DEFAULT AS IDENTITY (START WITH %s)', next);
END $$;

CREATE TABLE portal_calendar_sections (
    num         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     uuid UNIQUE REFERENCES users(id) ON DELETE CASCADE,          -- the person's main calendar
    calendar_id uuid UNIQUE REFERENCES user_calendars(id) ON DELETE CASCADE, -- one of the person's own
    project_id  uuid UNIQUE REFERENCES projects(id) ON DELETE CASCADE,       -- a project's (a collab's)
    company     boolean NOT NULL DEFAULT false,                               -- the company's
    CHECK (num_nonnulls(user_id, calendar_id, project_id) + company::int = 1)
);
CREATE UNIQUE INDEX portal_calendar_sections_company ON portal_calendar_sections (company) WHERE company;
