-- REST compatible with the portal, the feed (GO24DEV-948): integrations know posts and comments by numbers
-- (log.blogpost.get POST_ID, log.blogcomment.delete COMMENT_ID), given in the order of creation, never reused.
ALTER TABLE feed_posts ADD COLUMN num bigint;
UPDATE feed_posts x SET num = o.n FROM (SELECT id, row_number() OVER (ORDER BY created_at, id) n FROM feed_posts) o WHERE o.id = x.id;
ALTER TABLE feed_posts ALTER COLUMN num SET NOT NULL, ADD UNIQUE (num);
ALTER TABLE feed_comments ADD COLUMN num bigint;
UPDATE feed_comments x SET num = o.n FROM (SELECT id, row_number() OVER (ORDER BY created_at, id) n FROM feed_comments) o WHERE o.id = x.id;
ALTER TABLE feed_comments ALTER COLUMN num SET NOT NULL, ADD UNIQUE (num);
DO $$
DECLARE
    next bigint;
BEGIN
    SELECT coalesce(max(num), 0) + 1 FROM feed_posts INTO next;
    EXECUTE format('ALTER TABLE feed_posts ALTER COLUMN num ADD GENERATED BY DEFAULT AS IDENTITY (START WITH %s)', next);
    SELECT coalesce(max(num), 0) + 1 FROM feed_comments INTO next;
    EXECUTE format('ALTER TABLE feed_comments ALTER COLUMN num ADD GENERATED BY DEFAULT AS IDENTITY (START WITH %s)', next);
END $$;
