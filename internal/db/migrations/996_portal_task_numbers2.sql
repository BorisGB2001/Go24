-- REST compatible with the portal, tasks, step 2 (GO24DEV-995): time entries (task.elapseditem.*) and stages
-- (task.stages.*) get numbers too. The stages of groups and of «Мой план» are numbered in one row a
-- stage is known by its ID alone.
ALTER TABLE time_entries ADD COLUMN num bigint;
UPDATE time_entries x SET num = o.n FROM (SELECT id, row_number() OVER (ORDER BY created_at, id) n FROM time_entries) o
WHERE o.id = x.id;
ALTER TABLE time_entries ALTER COLUMN num SET NOT NULL, ADD UNIQUE (num);
DO $$
DECLARE
    next bigint;
BEGIN
    SELECT coalesce(max(num), 0) + 1 FROM time_entries INTO next;
    EXECUTE format('ALTER TABLE time_entries ALTER COLUMN num ADD GENERATED BY DEFAULT AS IDENTITY (START WITH %s)', next);
END $$;

CREATE SEQUENCE task_stage_num;
ALTER TABLE project_stages ADD COLUMN num bigint;
ALTER TABLE plan_stages ADD COLUMN num bigint;
UPDATE project_stages x SET num = o.n FROM (SELECT id, nextval('task_stage_num') n FROM
    (SELECT id FROM project_stages ORDER BY created_at, id) s) o WHERE o.id = x.id;
UPDATE plan_stages x SET num = o.n FROM (SELECT id, nextval('task_stage_num') n FROM
    (SELECT id FROM plan_stages ORDER BY created_at, id) s) o WHERE o.id = x.id;
ALTER TABLE project_stages ALTER COLUMN num SET DEFAULT nextval('task_stage_num'), ALTER COLUMN num SET NOT NULL, ADD UNIQUE (num);
ALTER TABLE plan_stages ALTER COLUMN num SET DEFAULT nextval('task_stage_num'), ALTER COLUMN num SET NOT NULL, ADD UNIQUE (num);
