-- REST compatible with the portal, CRM (GO24DEV-761): integrations know deals, leads, contacts, companies, pipelines
-- («CATEGORY_ID») and stages by numbers; the number is given once, in the order of creation, never reused (the recycle
-- bin restores a card with its number). The deal pipelines are numbered from 0 — the first is the main one
-- («CATEGORY_ID»: 0).
DO $$
DECLARE
    t    text;
    next bigint;
BEGIN
    FOREACH t IN ARRAY ARRAY['crm_deals', 'crm_leads', 'crm_contacts', 'crm_companies'] LOOP
        EXECUTE format('ALTER TABLE %I ADD COLUMN num bigint', t);
        EXECUTE format('UPDATE %I x SET num = o.n FROM (SELECT id, row_number() OVER (ORDER BY created_at, id) n FROM %I) o
                        WHERE o.id = x.id', t, t);
        EXECUTE format('ALTER TABLE %I ALTER COLUMN num SET NOT NULL, ADD UNIQUE (num)', t);
        EXECUTE format('SELECT coalesce(max(num), 0) + 1 FROM %I', t) INTO next;
        EXECUTE format('ALTER TABLE %I ALTER COLUMN num ADD GENERATED BY DEFAULT AS IDENTITY (START WITH %s)', t, next);
    END LOOP;
END $$;

ALTER TABLE crm_pipelines ADD COLUMN num bigint;
UPDATE crm_pipelines p SET num = o.n FROM (SELECT id, row_number() OVER (ORDER BY type_id IS NOT NULL, sort, created_at, id) - 1 n
                                           FROM crm_pipelines) o WHERE o.id = p.id;
ALTER TABLE crm_pipelines ALTER COLUMN num SET NOT NULL, ADD UNIQUE (num);
DO $$ BEGIN
    EXECUTE format('ALTER TABLE crm_pipelines ALTER COLUMN num ADD GENERATED BY DEFAULT AS IDENTITY (MINVALUE 0 START WITH %s)',
                   (SELECT coalesce(max(num), -1) + 1 FROM crm_pipelines));
END $$;

ALTER TABLE crm_stages ADD COLUMN num bigint;
UPDATE crm_stages s SET num = o.n FROM (SELECT id, row_number() OVER (ORDER BY entity, sort, id) n FROM crm_stages) o WHERE o.id = s.id;
ALTER TABLE crm_stages ALTER COLUMN num SET NOT NULL, ADD UNIQUE (num);
DO $$ BEGIN
    EXECUTE format('ALTER TABLE crm_stages ALTER COLUMN num ADD GENERATED BY DEFAULT AS IDENTITY (START WITH %s)',
                   (SELECT coalesce(max(num), 0) + 1 FROM crm_stages));
END $$;
