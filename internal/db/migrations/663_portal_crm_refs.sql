-- REST compatible with the portal, the CRM's lists and deeds (GO24DEV-834): crm.status.* gives the stages and the items
-- of the dictionaries in one list whose ID is unique, as the b_crm_status — so the items of crm_dict take
-- their numbers from the same sequence as the stages (migration 619); crm.activity.* knows a deed by its number.
CREATE SEQUENCE crm_status_num OWNED BY crm_stages.num;
ALTER TABLE crm_stages ALTER COLUMN num DROP IDENTITY;
ALTER TABLE crm_stages ALTER COLUMN num SET DEFAULT nextval('crm_status_num');

ALTER TABLE crm_dict ADD COLUMN num bigint;
UPDATE crm_dict d SET num = o.n + (SELECT coalesce(max(num), 0) FROM crm_stages)
    FROM (SELECT id, row_number() OVER (ORDER BY kind, sort, id) n FROM crm_dict) o WHERE o.id = d.id;
ALTER TABLE crm_dict ALTER COLUMN num SET NOT NULL, ALTER COLUMN num SET DEFAULT nextval('crm_status_num'), ADD UNIQUE (num);
SELECT setval('crm_status_num', greatest((SELECT max(num) FROM crm_stages), (SELECT max(num) FROM crm_dict), 1));

ALTER TABLE crm_activities ADD COLUMN num bigint;
UPDATE crm_activities a SET num = o.n FROM (SELECT id, row_number() OVER (ORDER BY created_at, id) n FROM crm_activities) o
    WHERE o.id = a.id;
ALTER TABLE crm_activities ALTER COLUMN num SET NOT NULL, ADD UNIQUE (num);
DO $$ BEGIN
    EXECUTE format('ALTER TABLE crm_activities ALTER COLUMN num ADD GENERATED BY DEFAULT AS IDENTITY (START WITH %s)',
                   (SELECT coalesce(max(num), 0) + 1 FROM crm_activities));
END $$;
