-- REST compatible with the portal (GO24DEV-760): integrations know employees and departments by numbers
-- ("ID": "1", UF_DEPARTMENT: [1]), go24 by uuid; the number is given once, in the order of creation, never reused.
ALTER TABLE users ADD COLUMN num bigint;
UPDATE users u SET num = o.n FROM (SELECT id, row_number() OVER (ORDER BY created_at, id) n FROM users) o WHERE o.id = u.id;
ALTER TABLE users ALTER COLUMN num SET NOT NULL, ADD UNIQUE (num);
DO $$ BEGIN
    EXECUTE format('ALTER TABLE users ALTER COLUMN num ADD GENERATED BY DEFAULT AS IDENTITY (START WITH %s)',
                   (SELECT coalesce(max(num), 0) + 1 FROM users));
END $$;

ALTER TABLE departments ADD COLUMN num bigint;
UPDATE departments d SET num = o.n FROM (SELECT id, row_number() OVER (ORDER BY parent_id IS NOT NULL, created_at, id) n
                                          FROM departments) o WHERE o.id = d.id;
ALTER TABLE departments ALTER COLUMN num SET NOT NULL, ADD UNIQUE (num);
DO $$ BEGIN
    EXECUTE format('ALTER TABLE departments ALTER COLUMN num ADD GENERATED BY DEFAULT AS IDENTITY (START WITH %s)',
                   (SELECT coalesce(max(num), 0) + 1 FROM departments));
END $$;
