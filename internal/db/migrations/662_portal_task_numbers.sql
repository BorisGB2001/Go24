-- REST compatible with the portal, tasks (GO24DEV-820): integrations know tasks, groups (projects), task comments and
-- checklist items by numbers; the number is given once, in the order of creation, never reused (the trash restores a
-- task with its number).
DO $$
DECLARE
    t    text;
    next bigint;
BEGIN
    FOREACH t IN ARRAY ARRAY['tasks_all', 'projects', 'task_comments', 'task_checklist_items'] LOOP
        EXECUTE format('ALTER TABLE %I ADD COLUMN num bigint', t);
        EXECUTE format('UPDATE %I x SET num = o.n FROM (SELECT id, row_number() OVER (ORDER BY created_at, id) n FROM %I) o
                        WHERE o.id = x.id', t, t);
        EXECUTE format('ALTER TABLE %I ALTER COLUMN num SET NOT NULL, ADD UNIQUE (num)', t);
        EXECUTE format('SELECT coalesce(max(num), 0) + 1 FROM %I', t) INTO next;
        EXECUTE format('ALTER TABLE %I ALTER COLUMN num ADD GENERATED BY DEFAULT AS IDENTITY (START WITH %s)', t, next);
    END LOOP;
END $$;

CREATE OR REPLACE VIEW tasks AS SELECT * FROM tasks_all WHERE deleted_at IS NULL; -- the new column (see 060)
