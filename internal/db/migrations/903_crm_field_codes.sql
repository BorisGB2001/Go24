-- REST compatible with the portal, user fields of the CRM (GO24DEV-957): an own field of deals, leads, contacts and
-- companies is UF_CRM_<code> — the code given by crm.*.userfield.add (FIELD_NAME), or its number, given once in the
-- order of creation and never reused.
DO $$
DECLARE
    t    text;
    next bigint;
BEGIN
    FOREACH t IN ARRAY ARRAY['crm_deal_fields', 'crm_lead_fields', 'crm_contact_fields', 'crm_company_fields'] LOOP
        EXECUTE format('ALTER TABLE %I ADD COLUMN num bigint, ADD COLUMN code text CHECK (code ~ ''^[A-Z0-9_]{1,40}$'')', t);
        EXECUTE format('UPDATE %I x SET num = o.n FROM (SELECT id, row_number() OVER (ORDER BY created_at, id) n FROM %I) o
                        WHERE o.id = x.id', t, t);
        EXECUTE format('ALTER TABLE %I ALTER COLUMN num SET NOT NULL, ADD UNIQUE (num), ADD UNIQUE (code)', t);
        EXECUTE format('SELECT coalesce(max(num), 0) + 1 FROM %I', t) INTO next;
        EXECUTE format('ALTER TABLE %I ALTER COLUMN num ADD GENERATED BY DEFAULT AS IDENTITY (START WITH %s)', t, next);
    END LOOP;
END $$;
