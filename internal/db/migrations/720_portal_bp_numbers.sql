-- REST compatible with the portal, workflows (GO24DEV-855): integrations know templates and tasks of workflows by
-- numbers (bizproc.workflow.template.list, bizproc.task.list); a process keeps its uuid — WORKFLOW_ID is a
-- string too. The number is given once, in the order of creation, never reused.
DO $$
DECLARE
    t    text;
    next bigint;
BEGIN
    FOREACH t IN ARRAY ARRAY['bp_templates', 'bp_approvals'] LOOP
        EXECUTE format('ALTER TABLE %I ADD COLUMN num bigint', t);
        EXECUTE format('UPDATE %I x SET num = o.n FROM (SELECT id, row_number() OVER (ORDER BY created_at, id) n FROM %I) o
                        WHERE o.id = x.id', t, t);
        EXECUTE format('ALTER TABLE %I ALTER COLUMN num SET NOT NULL, ADD UNIQUE (num)', t);
        EXECUTE format('SELECT coalesce(max(num), 0) + 1 FROM %I', t) INTO next;
        EXECUTE format('ALTER TABLE %I ALTER COLUMN num ADD GENERATED BY DEFAULT AS IDENTITY (START WITH %s)', t, next);
    END LOOP;
END $$;
