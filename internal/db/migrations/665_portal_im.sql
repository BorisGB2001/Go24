-- REST compatible with the portal, the messenger (GO24DEV-839): integrations know chats as «chatN» and messages by
-- numbers; a Matrix room or message gets its number when an integration first meets it, never reused.
CREATE TABLE portal_chats (
    num     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id text NOT NULL UNIQUE
);
CREATE TABLE portal_messages (
    num      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id  text NOT NULL,
    event_id text NOT NULL UNIQUE
);

-- im.notify.*: a notification of an integration (kind app — a system one, app_personal — from the caller); sent_by is
-- whose key sent it (im.notify.delete takes back only one's own), one with the same tag replaces the earlier one
ALTER TABLE notifications ADD COLUMN sent_by uuid REFERENCES users ON DELETE SET NULL,
                          ADD COLUMN tag text;
CREATE INDEX notifications_sent_by_idx ON notifications (sent_by, tag) WHERE sent_by IS NOT NULL;
