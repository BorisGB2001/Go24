-- REST compatible with the portal, user fields of tasks (GO24DEV-1000): an own field of tasks is UF_<code> — the code
-- given by task.item.userfield.add (FIELD_NAME), or UF_AUTO_<number>, the number given once in the order of creation
-- and never reused (as the fields of employees of 985).
ALTER TABLE task_fields ADD COLUMN num bigint, ADD COLUMN code text CHECK (code ~ '^[A-Z0-9_]{1,40}$');
UPDATE task_fields x SET num = o.n FROM (SELECT id, row_number() OVER (ORDER BY created_at, id) n FROM task_fields) o
WHERE o.id = x.id;
ALTER TABLE task_fields ALTER COLUMN num SET NOT NULL, ADD UNIQUE (num), ADD UNIQUE (code);
DO $$
DECLARE
    next bigint;
BEGIN
    SELECT coalesce(max(num), 0) + 1 FROM task_fields INTO next;
    EXECUTE format('ALTER TABLE task_fields ALTER COLUMN num ADD GENERATED BY DEFAULT AS IDENTITY (START WITH %s)', next);
END $$;
