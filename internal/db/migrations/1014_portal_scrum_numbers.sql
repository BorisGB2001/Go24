-- REST compatible with the portal, tasks, step 4 (GO24DEV-1014): tasks.api.scrum.* know sprints, epics and the backlog
-- by numbers. As, the backlog of a scrum and its sprints are numbered in one row (a task's entityId is
-- either); the backlog gets its number when it is first asked for. Who created a sprint is kept from now on.
CREATE SEQUENCE scrum_entity_num;
ALTER TABLE sprints ADD COLUMN num bigint, ADD COLUMN created_by uuid REFERENCES users(id) ON DELETE SET NULL;
UPDATE sprints x SET num = o.n FROM (SELECT id, nextval('scrum_entity_num') n FROM
    (SELECT id FROM sprints ORDER BY created_at, id) s) o WHERE o.id = x.id;
ALTER TABLE sprints ALTER COLUMN num SET DEFAULT nextval('scrum_entity_num'), ALTER COLUMN num SET NOT NULL, ADD UNIQUE (num);
ALTER TABLE projects ADD COLUMN backlog_num bigint UNIQUE;

ALTER TABLE epics ADD COLUMN num bigint;
UPDATE epics x SET num = o.n FROM (SELECT id, row_number() OVER (ORDER BY created_at, id) n FROM epics) o WHERE o.id = x.id;
ALTER TABLE epics ALTER COLUMN num SET NOT NULL, ADD UNIQUE (num);
DO $$
DECLARE
    next bigint;
BEGIN
    SELECT coalesce(max(num), 0) + 1 FROM epics INTO next;
    EXECUTE format('ALTER TABLE epics ALTER COLUMN num ADD GENERATED BY DEFAULT AS IDENTITY (START WITH %s)', next);
END $$;
