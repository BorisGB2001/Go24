-- REST compatible with the portal, workgroups (GO24DEV-940): SUBJECT_ID of sonet_group.* is the number of a group's
-- subject («Тематика»), given in the order of creation, never reused.
ALTER TABLE group_subjects ADD COLUMN num bigint;
UPDATE group_subjects x SET num = o.n FROM (SELECT id, row_number() OVER (ORDER BY created_at, id) n FROM group_subjects) o
 WHERE o.id = x.id;
DO $$
DECLARE next bigint;
BEGIN
    SELECT coalesce(max(num), 0) + 1 INTO next FROM group_subjects;
    ALTER TABLE group_subjects ALTER COLUMN num SET NOT NULL, ADD UNIQUE (num);
    EXECUTE format('ALTER TABLE group_subjects ALTER COLUMN num ADD GENERATED BY DEFAULT AS IDENTITY (START WITH %s)', next);
END $$;
