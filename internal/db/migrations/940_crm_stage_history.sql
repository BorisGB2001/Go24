-- REST compatible with the portal, crm.stagehistory.list (GO24DEV-976): how deals, leads and smart processes' cards went
-- through the stages, as b_crm_deal_stage_history. A trigger writes it, whatever moved the card (the kanban, a robot,
-- the REST, a stage deleted). kind as TYPE_ID: 1 created, 2 a working stage, 3 a final one, 5 another
-- pipeline. The cards made before keep one row: their stage now, at their creation.
CREATE TABLE crm_stage_history (
    num         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity      text NOT NULL,
    card_id     uuid NOT NULL,
    pipeline_id uuid REFERENCES crm_pipelines (id) ON DELETE CASCADE,
    stage_id    uuid NOT NULL REFERENCES crm_stages (id) ON DELETE CASCADE,
    kind        smallint NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX crm_stage_history_card_idx ON crm_stage_history (entity, card_id);
CREATE INDEX crm_stage_history_created_idx ON crm_stage_history (entity, created_at);

CREATE FUNCTION crm_stage_kind(stage uuid) RETURNS smallint LANGUAGE sql STABLE AS $$
    SELECT CASE semantic WHEN 'process' THEN 2 ELSE 3 END::smallint FROM crm_stages WHERE id = stage
$$;

CREATE FUNCTION crm_deal_stage_history() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'UPDATE' AND NEW.stage_id = OLD.stage_id AND NEW.pipeline_id = OLD.pipeline_id THEN
        RETURN NULL;
    END IF;
    INSERT INTO crm_stage_history (entity, card_id, pipeline_id, stage_id, kind)
    VALUES ('deal', NEW.id, NEW.pipeline_id, NEW.stage_id, CASE
        WHEN TG_OP = 'INSERT' THEN 1
        WHEN NEW.pipeline_id <> OLD.pipeline_id THEN 5
        ELSE crm_stage_kind(NEW.stage_id) END);
    RETURN NULL;
END $$;

CREATE FUNCTION crm_lead_stage_history() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'UPDATE' AND NEW.stage_id = OLD.stage_id THEN
        RETURN NULL;
    END IF;
    INSERT INTO crm_stage_history (entity, card_id, stage_id, kind)
    VALUES ('lead', NEW.id, NEW.stage_id, CASE WHEN TG_OP = 'INSERT' THEN 1 ELSE crm_stage_kind(NEW.stage_id) END);
    RETURN NULL;
END $$;

CREATE TRIGGER crm_deals_stage_history AFTER INSERT OR UPDATE OF stage_id, pipeline_id ON crm_deals
    FOR EACH ROW EXECUTE FUNCTION crm_deal_stage_history();
CREATE TRIGGER crm_leads_stage_history AFTER INSERT OR UPDATE OF stage_id ON crm_leads
    FOR EACH ROW EXECUTE FUNCTION crm_lead_stage_history();

INSERT INTO crm_stage_history (entity, card_id, pipeline_id, stage_id, kind, created_at)
SELECT 'deal', id, pipeline_id, stage_id, 1, created_at FROM crm_deals
UNION ALL
SELECT 'lead', id, NULL, stage_id, 1, created_at FROM crm_leads
ORDER BY 6;
