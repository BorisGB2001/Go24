-- REST compatible with the portal, user fields of employees (GO24DEV-985): an own field of the profile is UF_USR_<code>
-- — the code given by user.userfield.add (FIELD_NAME), or its number, given once in the order of creation and never
-- reused (as the CRM fields of 903).
ALTER TABLE user_fields ADD COLUMN num bigint, ADD COLUMN code text CHECK (code ~ '^[A-Z0-9_]{1,40}$');
UPDATE user_fields x SET num = o.n FROM (SELECT id, row_number() OVER (ORDER BY created_at, id) n FROM user_fields) o
WHERE o.id = x.id;
ALTER TABLE user_fields ALTER COLUMN num SET NOT NULL, ADD UNIQUE (num), ADD UNIQUE (code);
DO $$
DECLARE
    next bigint;
BEGIN
    SELECT coalesce(max(num), 0) + 1 FROM user_fields INTO next;
    EXECUTE format('ALTER TABLE user_fields ALTER COLUMN num ADD GENERATED BY DEFAULT AS IDENTITY (START WITH %s)', next);
END $$;
