-- REST compatible with the portal, the products of the CRM (GO24DEV-928): crm.product.*, crm.productsection.*,
-- crm.measure.list and the rows' STORE_ID know the products, the catalog's sections, the units and the warehouses by
-- numbers, given once in the order of creation, as the other numbers of the CRM (migration 619). A product row's
-- number is its id.
DO $$
DECLARE
    t     text;
    ord   text;
    next  bigint;
BEGIN
    FOREACH t IN ARRAY ARRAY['crm_products', 'crm_product_sections', 'crm_units', 'crm_warehouses'] LOOP
        ord := CASE WHEN t = 'crm_units' THEN 'sort, code, id' ELSE 'created_at, id' END;
        EXECUTE format('ALTER TABLE %I ADD COLUMN num bigint', t);
        EXECUTE format('UPDATE %I x SET num = o.n FROM (SELECT id, row_number() OVER (ORDER BY %s) n FROM %I) o
                        WHERE o.id = x.id', t, ord, t);
        EXECUTE format('ALTER TABLE %I ALTER COLUMN num SET NOT NULL, ADD UNIQUE (num)', t);
        EXECUTE format('SELECT coalesce(max(num), 0) + 1 FROM %I', t) INTO next;
        EXECUTE format('ALTER TABLE %I ALTER COLUMN num ADD GENERATED BY DEFAULT AS IDENTITY (START WITH %s)', t, next);
    END LOOP;
END $$;
